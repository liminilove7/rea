const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root=__dirname;
(async()=>{
  const checks=[],errors=[],network=[];
  const check=(name,value)=>{assert.ok(value,name);checks.push({name,passed:true});};
  const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    page.on('pageerror',e=>errors.push(String(e)));
    page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
    await page.goto(pathToFileURL(path.join(root,'攻速修改方案与后续计划.html')).href);
    await page.waitForFunction(()=>window.labReport);
    check('Six report sections',await page.locator('section').count()===6);
    check('Two technical diagrams',await page.locator('svg').count()===2);
    check('Actual app preview loads',await page.locator('img').evaluate(i=>i.complete&&i.naturalWidth===1000));
    check('All five future stages included',await page.locator('#plan .stage').count()===5);
    check('Server-hit-rate limit explicit',(await page.locator('#status').textContent()).includes('不能把'));
    check('Stealth scope excluded',(await page.locator('#implementation').textContent()).includes('不提供强反检测'));
    const original=await page.evaluate(()=>labReport.calculateAddresses('0x3760000','0x73956000'));
    check('Known base plus offsets',original.I==='0x4b8db40'&&original.Mirror==='0x4b8dc10'&&original.V==='0x73956532');
    await page.locator('#base').fill('0x4000000');
    check('ASLR example updates',(await page.locator('#addresses').textContent()).includes('0x542db40'));
    await page.locator('#character').fill('0xc3b14000');
    check('Object example updates',(await page.locator('#addresses').textContent()).includes('0xc3b14532'));
    await page.locator('#base').fill('bad');
    check('Invalid input has clear error',(await page.locator('#addresses').textContent()).includes('十六进制'));
    await page.locator('#base').fill('0x3760000');await page.locator('#character').fill('0x73956000');
    const links=await page.locator('a[href]').evaluateAll(xs=>xs.map(x=>x.getAttribute('href')));
    check('All relative artifact links exist',links.filter(h=>!h.startsWith('#')&&h!=='browser-verification.json').every(h=>fs.existsSync(path.resolve(root,h))));
    check('All navigation anchors resolve',await page.evaluate(()=>[...document.querySelectorAll('a[href^="#"]')].every(a=>document.querySelector(a.getAttribute('href')))));
    check('Desktop no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(root,'report-preview.png')});
    await page.locator('#plan').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(root,'plan-preview.png')});
    await page.setViewportSize({width:390,height:844});await page.evaluate(()=>scrollTo(0,0));
    check('Mobile no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(root,'report-mobile.png')});
    await page.locator('#offsets').scrollIntoViewIfNeeded();
    check('Mobile offsets have no overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.emulateMedia({media:'print'});
    check('Print keeps all stages',await page.locator('#plan .stage').count()===5);
    check('No external network',network.length===0);check('No JS errors',errors.length===0);
    fs.writeFileSync(path.join(root,'browser-verification.json'),JSON.stringify({allPassed:true,checks,errors,network,newGuiGameWriteTested:false},null,2));
    console.log(JSON.stringify({allPassed:true,checks:checks.length}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
